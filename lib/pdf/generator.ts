import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Asset, ServiceRecord, Warranty } from '../db/schema';

export function generateWarrantyClaimPDF(
  asset: Asset,
  warranty: Warranty,
  serviceRecords: ServiceRecord[]
): jsPDF {
  const doc = new jsPDF();

  // Header Banner
  doc.setFillColor(15, 118, 110); // brand teal-700
  doc.rect(0, 0, 210, 35, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('ASSETCARE', 14, 18);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text('OFFICIAL WARRANTY CLAIM HISTORY DOSSIER', 14, 26);

  // Claim Status Badge
  doc.setFillColor(236, 253, 245);
  doc.roundedRect(150, 10, 46, 16, 2, 2, 'F');
  doc.setTextColor(5, 150, 105);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('STATUS: ACTIVE', 154, 20);

  // Asset Details Section
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('1. ASSET IDENTIFICATION', 14, 48);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');

  const assetDetails = [
    ['Asset Name:', asset.name, 'Category:', asset.category_name || 'Vehicle/Appliance'],
    ['Brand & Model:', `${asset.brand} - ${asset.model}`, 'Location:', asset.location || 'N/A'],
    ['Serial Number:', asset.serial_number || 'N/A', 'Registration #:', asset.registration_number || 'N/A'],
    ['Purchase Date:', asset.purchase_date || 'N/A', 'Original Price:', `INR ${asset.purchase_price.toLocaleString('en-IN')}`],
  ];

  autoTable(doc, {
    startY: 52,
    body: assetDetails,
    theme: 'plain',
    styles: { fontSize: 9, cellPadding: 2 },
    columnStyles: {
      0: { fontStyle: 'bold', textColor: [100, 116, 139], cellWidth: 32 },
      1: { cellWidth: 65 },
      2: { fontStyle: 'bold', textColor: [100, 116, 139], cellWidth: 32 },
      3: { cellWidth: 65 },
    },
  });

  // Warranty Coverage Section
  const nextY = (doc as any).lastAutoTable.finalY + 8;
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('2. WARRANTY COVERAGE PARTICULARS', 14, nextY);

  const warrantyData = [
    ['Component Protected:', warranty.component],
    ['Warranty Category:', warranty.warranty_type === 'repair_service' ? 'Service / Repair Warranty' : 'Manufacturer Warranty'],
    ['Effective Start Date:', warranty.start_date],
    ['Duration:', `${warranty.duration_months} Months`],
    ['Coverage Expiry Date:', warranty.expiry_date],
    ['Authorized Provider:', warranty.provider],
    ['Documented Conditions:', warranty.conditions || 'Standard coverage against component defect & repair workmanship.'],
    ['Internal Claim Notes:', warranty.notes || 'None logged.'],
  ];

  autoTable(doc, {
    startY: nextY + 4,
    body: warrantyData,
    theme: 'striped',
    styles: { fontSize: 9, cellPadding: 2.5 },
    columnStyles: {
      0: { fontStyle: 'bold', textColor: [30, 41, 59], cellWidth: 55 },
      1: { textColor: [51, 65, 85], cellWidth: 135 },
    },
  });

  // Supporting Invoices & Repair History
  const historyY = (doc as any).lastAutoTable.finalY + 8;
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('3. SUPPORTING SERVICE & REPAIR INVOICES', 14, historyY);

  const tableRows = serviceRecords.map((s) => [
    s.service_date,
    s.invoice_number || 'N/A',
    s.vendor_name,
    s.component,
    s.description_of_work,
    `INR ${s.total_amount.toLocaleString('en-IN')}`,
    `${s.warranty_duration_months || 0} Mo.`,
  ]);

  autoTable(doc, {
    startY: historyY + 4,
    head: [['Date', 'Invoice #', 'Service Provider', 'Component', 'Work Done', 'Amount', 'Warranty']],
    body: tableRows,
    headStyles: { fillColor: [15, 118, 110], textColor: [255, 255, 255], fontStyle: 'bold' },
    styles: { fontSize: 8, cellPadding: 2.5 },
    columnStyles: {
      0: { cellWidth: 20 },
      1: { cellWidth: 22 },
      2: { cellWidth: 32 },
      3: { cellWidth: 28 },
      4: { cellWidth: 46 },
      5: { cellWidth: 22, halign: 'right' },
      6: { cellWidth: 18, halign: 'center' },
    },
  });

  // Footer Disclaimer
  const pageCount = (doc.internal as any).getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      'Generated by AssetCare Digital Vault. This verified document provides chronological maintenance proof for warranty presentation.',
      14,
      288
    );
    doc.text(`Page ${i} of ${pageCount}`, 190, 288, { align: 'right' });
  }

  return doc;
}

export function generateAssetExpenseReportPDF(
  asset: Asset,
  serviceRecords: ServiceRecord[]
): jsPDF {
  const doc = new jsPDF();

  // Header Banner
  doc.setFillColor(30, 41, 59); // slate-800
  doc.rect(0, 0, 210, 32, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text(asset.name, 14, 16);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`AssetCare Lifetime Maintenance & Cost-of-Ownership Statement`, 14, 24);

  // Financial Summary Cards
  const totalRepair = serviceRecords
    .filter((s) => s.service_type === 'repair')
    .reduce((sum, s) => sum + s.total_amount, 0);

  const totalServicing = serviceRecords
    .filter((s) => s.service_type !== 'repair')
    .reduce((sum, s) => sum + s.total_amount, 0);

  const totalSpent = asset.purchase_price + totalRepair + totalServicing;

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('FINANCIAL SUMMARY', 14, 42);

  const summary = [
    ['Original Purchase Price:', `INR ${asset.purchase_price.toLocaleString('en-IN')}`, 'Total Invoices Recorded:', `${serviceRecords.length}`],
    ['Total Repair Expenditure:', `INR ${totalRepair.toLocaleString('en-IN')}`, 'Routine Servicing Spend:', `INR ${totalServicing.toLocaleString('en-IN')}`],
    ['Total Cost of Ownership:', `INR ${totalSpent.toLocaleString('en-IN')}`, 'Vehicle / Asset Status:', 'Operational'],
  ];

  autoTable(doc, {
    startY: 46,
    body: summary,
    theme: 'plain',
    styles: { fontSize: 9, cellPadding: 2 },
    columnStyles: {
      0: { fontStyle: 'bold', textColor: [100, 116, 139], cellWidth: 45 },
      1: { cellWidth: 50 },
      2: { fontStyle: 'bold', textColor: [100, 116, 139], cellWidth: 45 },
      3: { cellWidth: 50 },
    },
  });

  // Chronological Invoices
  const nextY = (doc as any).lastAutoTable.finalY + 8;
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('CHRONOLOGICAL SERVICE & REPAIR LOG', 14, nextY);

  const rows = serviceRecords.map((s) => [
    s.service_date,
    s.invoice_number || 'N/A',
    s.vendor_name,
    s.component,
    s.service_type === 'repair' ? 'Repair' : 'Servicing',
    s.description_of_work,
    `INR ${s.total_amount.toLocaleString('en-IN')}`,
  ]);

  autoTable(doc, {
    startY: nextY + 4,
    head: [['Date', 'Inv #', 'Vendor', 'Component', 'Type', 'Description', 'Total']],
    body: rows,
    headStyles: { fillColor: [30, 41, 59], textColor: [255, 255, 255] },
    styles: { fontSize: 8, cellPadding: 2.5 },
    columnStyles: {
      0: { cellWidth: 20 },
      1: { cellWidth: 22 },
      2: { cellWidth: 32 },
      3: { cellWidth: 28 },
      4: { cellWidth: 20 },
      5: { cellWidth: 44 },
      6: { cellWidth: 22, halign: 'right' },
    },
  });

  return doc;
}

export function exportServiceRecordsCSV(records: ServiceRecord[]): string {
  const headers = [
    'Date',
    'Invoice Number',
    'Vendor Name',
    'Phone',
    'GSTIN',
    'Service Type',
    'Component',
    'Description',
    'Labour Charges',
    'Material Charges',
    'Discount',
    'GST',
    'Total Amount',
    'Payment Mode',
    'Warranty Months',
    'Warranty Expiry',
  ];

  const escapeCSV = (val: any) => {
    const s = String(val ?? '').replace(/"/g, '""');
    return `"${s}"`;
  };

  const lines = records.map((r) => [
    escapeCSV(r.service_date),
    escapeCSV(r.invoice_number),
    escapeCSV(r.vendor_name),
    escapeCSV(r.vendor_phone),
    escapeCSV(r.gstin),
    escapeCSV(r.service_type),
    escapeCSV(r.component),
    escapeCSV(r.description_of_work),
    escapeCSV(r.labour_charges),
    escapeCSV(r.material_charges),
    escapeCSV(r.discount),
    escapeCSV(r.gst_amount),
    escapeCSV(r.total_amount),
    escapeCSV(r.payment_mode),
    escapeCSV(r.warranty_duration_months),
    escapeCSV(r.warranty_expiry_date),
  ].join(','));

  return [headers.join(','), ...lines].join('\n');
}
